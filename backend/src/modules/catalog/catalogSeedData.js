export async function seedCatalogSources(demoBoardUrl = 'http://localhost:4000/demo/board') {
  const entries = [
    {
      name: 'Khabri Demo Notice Board',
      url: demoBoardUrl,
      type: 'listing',
      category: 'exam',
      state: 'All India',
      language: 'en',
      trust: 'official',
      isDemo: true,
      intervalMin: 15,
    },
    ...VERIFIED_CATALOG_SOURCES.map((s) => ({ ...s, isDemo: false })),
  ];

  for (const entry of entries) {
    await Source.findOneAndUpdate(
      { url: entry.url },
      {
        $set: {
          name: entry.name,
          type: entry.type,
          category: entry.category,
          state: entry.state,
          language: entry.language,
          trust: entry.trust,
          isDemo: entry.isDemo,
          intervalMin: entry.intervalMin,
        },
        $setOnInsert: {
          nextDueAt: new Date(),
          followerCount: 0,
        },
      },
      { upsert: true, returnDocument: 'after', setDefaultsOnInsert: true },
    );
  }

  return entries.length;
}
